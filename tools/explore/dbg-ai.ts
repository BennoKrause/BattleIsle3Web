import { NodeSource } from '../lib/node-source.ts';
import { loadGameData } from '../../src/data/gamedata.ts';
import { createGame } from '../../src/engine/setup.ts';
import { Game } from '../../src/engine/game.ts';
import { OriginalAI } from '../../src/engine/ai-original.ts';
const data = await loadGameData(new NodeSource());
const g = new Game(data, createGame(data, await data.loadMission(104), { setId: 0, difficulty: 1 }));
g.start();
const p = g.state.shops.find((sh) => sh.owner < 6 && sh.owner !== 0)!.owner;
for (let i = 0; i < 12 && g.state.activePlayer !== p; i++) g.endTurn();
const shop = g.state.shops.find((sh) => sh.owner === p)!;
const u = g.unitsOf(p).find((x) => !x.container && g.shopEntrySlot(shop.id, x.id) >= 0 && g.canMove(x))!;
u.group = 1;
const ai = new OriginalAI(g) as any;
ai.begin();
console.log('unit', u.id, data.unitClasses[u.type].name, 'at', u.x, u.y, 'shop', shop.x, shop.y, 'order', ai.orders.get(u.id), 'occupy', !!(data.unitClasses[u.type].flags & 8));
const tgt = ai.orders.get(u.id).target;
console.log('path', ai.path(u, tgt, false)?.length, 'step', ai.stepTowards(u, tgt, 2), 'reach', g.moveArea(u.id).targets.size);
for (let i = 0; i < 500 && ai.step(); i++);
console.log('after', u.x, u.y, u.container);
