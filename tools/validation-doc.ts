// Generates docs/testing/CAMPAIGN_VALIDATION.md from the recorded evidence:
//   research/e2e-results.json (npx playwright test) and research/campaign-run.json (tools/campaign-run.ts).
import { readFileSync, writeFileSync } from 'node:fs';

const inv = JSON.parse(readFileSync('docs/campaign/MISSION_INVENTORY.json', 'utf8'));
const run = JSON.parse(readFileSync('research/campaign-run.json', 'utf8'));
const e2e = JSON.parse(readFileSync('research/e2e-results.json', 'utf8'));
const passed = new Map<number, boolean>();
const walk = (suite: any) => {
  for (const s of suite.suites ?? []) walk(s);
  for (const sp of suite.specs ?? []) {
    const m = /^MISS(\d+) loads/.exec(sp.title);
    if (m) passed.set(Number(m[1]), sp.tests.every((t: any) => t.results.every((r: any) => r.status === 'passed')));
  }
};
for (const s of e2e.suites) walk(s);

const rows = inv.missions.map((m: any) => {
  const r = run[m.fileId];
  const loaded = passed.get(m.fileId) ? 'yes' : 'NOT TESTED / FAILED';
  const ai = !r ? '–' : r.error ? `ERROR ${r.error}` : r.outcome ? `${r.outcome.result} T${r.outcome.turn}` : `none in ${r.turn} turns`;
  return `| ${m.id} | ${m.setName} | ${m.name} | ${loaded} | ${loaded === 'yes' ? 'engine API only' : '–'} | ${ai} |`;
});

const md = `# Campaign validation (evidence-based)

Generated by \`tools/validation-doc.ts\` from \`research/e2e-results.json\` (Playwright) and
\`research/campaign-run.json\` (\`tools/campaign-run.ts\`). Nothing below is claimed without a recorded test.

## What the columns mean

- **Loaded (E2E)**: \`e2e/missions.spec.ts\` opens the mission in Chromium, no script error, map canvas drawn.
- **Moved a unit**: a unit of the active human player was moved to the farthest reachable field through the
  engine API inside the browser (technical playability, **not** a human playthrough).
- **AI-vs-AI run**: all sides computer-controlled (provisional AI, Normal, max. 40 turns, headless, Node).
  A *defeat* of player 0 here only shows the heuristic AI is weak, not that the mission is broken. A mission
  that ends with *none* simply did not finish in 40 turns.

## Results per mission

| Mission | Set | Name | Loaded (E2E) | Moved a unit | AI-vs-AI run |
|---|---|---|---|---|---|
${rows.join('\n')}

## Other evidence

| Area | Test | Result |
|---|---|---|
| Videos | \`e2e/videos.spec.ts\`: 142 converted MP4 files decode in Chromium (H.264/AAC) | see \`research/e2e-results.json\` |
| Known bad video | API900 (unreferenced 7-frame test clip): ffmpeg decodes only 1 frame | excluded, documented |
| Save/load | \`e2e/saves.spec.ts\` MISS100: save to localStorage, reload page, load -> identical state | passed |
| Campaign transition | \`e2e/campaign.spec.ts\`: forced victory of MISS100 -> next map MISS101, progress recorded | passed (victory is forced, proves transition only) |
| Rules / formats / MIDI | \`tests/*.test.ts\` (vitest) | all passing at last run |
| Music | \`e2e/music.spec.ts\`: file choice, running audio context, non-zero output, stops during video, loops | passed |

## Not verified (open)

- No mission has been completed by a human or by the AI as the *player* in the real UI; mission completability
  (events, victory conditions reached by play) is **not demonstrated** for any mission except the AI-vs-AI
  victories listed above (which show the victory condition code path works for those maps).
- Saves were only tested on MISS100; campaign save/continue across missions only via forced victory.
- Per-mission video playback inside the game flow (briefing/victory/defeat) is not tested; only decodability.
- The original computer opponent is not reconstructed; difficulty/behaviour differ from the original.
- No comparison against the original EXE running side by side (reference comparison: none).
- MIDI music: track selection (M_/A_ + mission number in the set, max. 19), looping, stopping during videos and
  non-silent output are tested (\`e2e/music.spec.ts\`), but the *sound* is a built-in approximation (no sound font);
  it does not sound like the original sound card / Windows synthesizer. Music in the DISK menu and exact start/stop
  moments of the original (menus, combat) are unverified.
- Fight window ("Schneller Kampf"): rebuilt from the decompiled MS_FIGTR.DLL (docs/research/GAME_RULES.md section 5);
  bar rules unit-tested, window opens/closes in E2E. No pixel comparison with the running original (no reference capture).
- 3D fight: models/textures/palettes/sounds of FGT/*.LIB are decoded (docs/research/FORMAT_3DO2.md) and shown in a re-implemented scene
  with the original window frame and statistics panel; tested headless (render determinism, visible explosions, sound cues) and in the browser.
  The camera script, formation, turret animation and landscape objects of the original (WC_FIGTR.DLL) are NOT reconstructed, so the scene is not identical to the original.
- Mission/game sound effects other than fight sounds (FX libraries of the game itself) are not implemented.
`;
writeFileSync('docs/testing/CAMPAIGN_VALIDATION.md', md);
console.log('written', rows.length, 'rows');
